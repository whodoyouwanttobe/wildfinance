"""
wb_parser.py — Анализ детализированного финансового отчёта Wildberries.

Рефакторинг: функция analyze() возвращает строку вместо print().

Поддерживает два формата входных файлов:
  - CSV  (.csv)
  - Excel (.xlsx / .xls)

И два набора столбцов (автоматическое определение):
  A) Формат реального отчёта WB:
     - 'К перечислению за товар', 'Стоимость логистики',
     - 'Общая сумма штрафов', 'Стоимость хранения', 'Стоимость платной приемки'
  B) Упрощённый формат:
     - 'К перечислению Продавцу за реализованный товар',
     - 'Услуги по доставке товара покупателю',
     - 'Общая сумма штрафов', 'Хранение', 'Операции при приёмке', 'Удержания'

Вывод: HTML-форматированный текст с эмодзи.
"""

