def detect_column_mapping(df: pd.DataFrame) -> dict:
    """Автоматически определяет формат отчёта по наличию столбцов."""
    cols = set(df.columns)
    if COLUMNS_A["доход"] in cols:
        return COLUMNS_A
    if COLUMNS_B["доход"] in cols:
        return COLUMNS_B
    return COLUMNS_B


def safe_col(df: pd.DataFrame, col_name: str) -> pd.Series:
    """Безопасно возвращает столбец; если его нет — серию нулей."""
    if col_name in df.columns:
        return to_num(df[col_name])
    return pd.Series(0.0, index=df.index)


def load_report(filepath: str) -> pd.DataFrame:
    """Читает CSV или Excel-файл."""
    return read_table(filepath)


def fmt(value: float) -> str:
    """Форматирует число с разделителями тысяч и 2 знаками после запятой."""
    return f"{value:,.2f}"


def bold(text: str) -> str:
    """Оборачивает текст в HTML-тег <b>."""
    return f"<b>{text}</b>"


def fmt_expense(value: float) -> str:
    """Форматирует расход: если > 0, выделяет жирным как отрицательный."""
    if value > 0:
        return bold(f"-{fmt(value)}")
    return fmt(value)


def fmt_profit(value: float) -> str:
    """Форматирует прибыль: отрицательные — жирным."""
    if value < 0:
        return bold(fmt(value))
    return fmt(value)


def generate_insight(артикул: str, row) -> str:
    """
    Эвристический «Советник» с фокусом на три главные боли селлера:
      1. Покатушки / фейковые заказы конкурентов
      2. Отказы, съедающие маржу
      3. Утери и штрафы без реализации

    Боль 1 усилена условием «поездок >= 2 при нулевых продажах»,
    чтобы не давать false positive на одиночный дефолтный возврат покупателя.
    """
    доход       = float(row.get("доход", 0))
    логистика   = float(row.get("логистика", 0))
    штрафы      = float(row.get("штрафы", 0))
    удержания   = float(row.get("удержания", 0))
    хранение    = float(row.get("хранение", 0))
    приёмка     = float(row.get("приёмка", 0))
    чистая      = float(row.get("чистая_прибыль", 0))
    поездок     = int(row.get("поездок", 0))
    продаж      = int(row.get("продаж_колво", 0))

    # ─── БОЛЬ 1: Покатушки / атака конкурентов ─────────────────────────────
    # Усиленный триггер: доход == 0, продаж нет, НО поездок >= 2.
    # Одиночный дефолтный возврат (поездок == 1) не считается аномалией.
    if доход <= 0 and продаж == 0 and поездок >= 2 and логистика > 0:
        return (
            "🚨 <b>Обнаружена аномалия:</b> товар ездит, но не выкупается. "
            f"{поездок} логистических операций при нулевых продажах, "
            f"логистика {fmt(логистика)} руб.\n"
            "   <b>Возможна атака конкурентов.</b>\n"
            "   ➡️ <b>Рекомендация:</b> проверьте регион заказов в кабинете ВБ "
            "и отключите доставку в эту гео-зону, либо обнулите остаток, "
            "чтобы остановить слив бюджета на логистику."
        )

    # ─── БОЛЬ 2: Отказы, съедающие маржу (> 40% чека) ─────────────────────
    # Логистика + штрафы + удержания — больше 40% от выручки.
    if доход > 0:
        доля_расходов_проц = ((логистика + штрафы + удержания) / доход) * 100
        if доля_расходов_проц > 40:
            # Рассчитываем наценку ТОЛЬКО если селлер в минусе.
            # Если уже в плюсе — показываем предупреждение без конкретной суммы.
            if чистая < 0:
                # Маржа отрицательная → считаем, на сколько надо поднять цену,
                # чтобы выйти в ноль + заложить 30% маржи.
                целевая_маржа_проц = 30
                недостача_проц = 100 - доля_расходов_проц + целевая_маржа_проц
                средний_чек = max(доход, 1)
                реком_наценка = round((недостача_проц / 100) * средний_чек)

                return (
                    f"📉 <b>Высокий процент отказов.</b> Логистика и штрафы "
                    f"съедают <b>{round(доля_расходов_проц)}%</b> от чека.\n"
                    "   ➡️ <b>Рекомендация:</b> пересчитайте юнит-экономику. "
                    f"Поднимите цену на <b>{fmt(реком_наценка)} руб.</b> или "
                    "выводите товар из ассортимента — сейчас вы работаете в минус."
                )
            else:
                # В плюсе, но расходы > 40% — это «жёлтая зона», не критично
                return (
                    f"📉 <b>Высокий процент отказов.</b> Логистика и штрафы "
                    f"съедают <b>{round(доля_расходов_проц)}%</b> от чека "
                    f"(маржа всего <b>{round(100 - доля_расходов_проц)}%</b>).\n"
                    "   ➡️ <b>Рекомендация:</b> снизьте логистические расходы "
                    "(габариты упаковки, % выкупа) — вы в плюсе, но с маленькой маржой "
                    "одна проблема с поставщиком убьёт прибыль."
                )

    # ─── БОЛЬ 3: Штрафы/удержания без реализации (потери/подмены) ──────────
    if (штрафы > 0 or удержания > 0) and доход <= 0:
        сумма_штрафов = штрафы + удержания
        return (
            f"⚠️ <b>Зафиксированы штрафы/удержания без реализации:</b> "
            f"{fmt(сумма_штрафов)} руб.\n"
            "   ➡️ <b>Рекомендация:</b> скопируйте штрихкод этого артикула "
            "и создайте тикет в поддержку ВБ на компенсацию утерянного товара."
        )

    # ─── Доп. сигнал: товар «завис» на складе ──────────────────────────────
    if чистая < 0 and хранение > 0 and хранение >= max(штрафы, удержания, логистика):
        return (
            f"📦 <b>Товар «завис» на складе:</b> хранение {fmt(хранение)} руб. "
            "съедает маржу.\n"
            "   ➡️ <b>Рекомендация:</b> добавьте артикул в акцию или снизьте цену, "
            "чтобы разгрузить остатки."
        )

    return ""


def compute(filepath: str) -> dict:
    """
    Считает все метрики отчёта без форматирования.
    Возвращает dict: итоги (доход, логистика, ..., чистая_прибыль) + grouped (DataFrame по артикулам).
    Используется в analyze() и в /compare.
    """
    df = load_report(filepath)
    col = detect_column_mapping(df)

    col_артикул     = col.get("артикул", "Артикул поставщика")
    col_обоснование = col.get("обоснование", "Обоснование для оплаты")
    col_доход       = col.get("доход", "")
    col_логистика   = col.get("логистика", "")
    col_штрафы      = col.get("штрафы", "")
    col_хранение    = col.get("хранение", "")
    col_приёмка     = col.get("приёмка", "")
    col_удержания   = col.get("удержания", "")

    # Безопасно получаем числовые серии
    доход_все     = safe_col(df, col_доход)
    логистика_все = safe_col(df, col_логистика)
    штрафы_все    = safe_col(df, col_штрафы)
    хранение_все  = safe_col(df, col_хранение)
    приёмка_все   = safe_col(df, col_приёмка)
    удержания_все = safe_col(df, col_удержания)
    for col_name in EXTRA_DEDUCTIONS["удержания"]:
        удержания_все = удержания_все + safe_col(df, col_name)
    for col_name in EXTRA_DEDUCTIONS["логистика"]:
        логистика_все = логистика_все + safe_col(df, col_name)

    # Доход = продажи − возвраты. В реальном отчёте WB это «Тип документа»
    # (Продажа / Возврат); в упрощённых файлах — «Обоснование для оплаты».
    обоснование = (
        df[col_обоснование].astype(str).str.strip().str.lower()
        if col_обоснование in df.columns else pd.Series("", index=df.index)
    )
    if COL_ТИП_ДОКУМЕНТА in df.columns:
        тип = df[COL_ТИП_ДОКУМЕНТА].astype(str).str.strip().str.lower()
        маска_продажа = тип == "продажа"
        маска_возврат = тип == "возврат"
    elif col_обоснование in df.columns:
        маска_продажа = обоснование == "продажа"
        маска_возврат = обоснование == "возврат"
    else:
        маска_продажа = pd.Series(True, index=df.index)
        маска_возврат = pd.Series(False, index=df.index)

    # Сумма возврата в разных выгрузках бывает и «+», и «−» — вычитаем по модулю
    доход_продажи = доход_все.where(маска_продажа, 0) - доход_все.where(маска_возврат, 0).abs()

    # A) Общая чистая прибыль
    общий_доход     = доход_продажи.sum()
    общая_логистика = логистика_все.sum()
    общие_штрафы    = штрафы_все.sum()
    общее_хранение  = хранение_все.sum()
    общая_приёмка   = приёмка_все.sum()
    общие_удержания = удержания_все.sum()
    общие_расходы   = общая_логистика + общие_штрафы + общее_хранение + общая_приёмка + общие_удержания
    чистая_прибыль  = общий_доход - общие_расходы

    # Б) Чистая прибыль по каждому артикулу
    df["_доход_продажи"] = доход_продажи
    df["_логистика"]     = логистика_все
    df["_штрафы"]        = штрафы_все
    df["_хранение"]      = хранение_все
    df["_приёмка"]       = приёмка_все
    df["_удержания"]     = удержания_все

    if col_артикул in df.columns:
        df["_артикул"] = df[col_артикул].fillna("").astype(str).str.strip()
    else:
        df["_артикул"] = ""

    # Счётчик поездок: строки логистики. В старых отчётах WB обоснование
    # называется «Логистика», в новых — «Доставка».
    if col_обоснование in df.columns:
        df["_есть_логистика"] = обоснование.str.contains("логистика|доставка", regex=True, na=False).astype(int)
        df["_есть_продажа"] = (обоснование == "продажа").astype(int)
        df["_есть_возврат"] = (обоснование == "возврат").astype(int)
    else:
        df["_есть_логистика"] = 0
        df["_есть_продажа"] = 0
        df["_есть_возврат"] = 0
    # Проданные штуки (продажи − возвраты) и выручка по цене для покупателя
    qty = safe_col(df, COL_КОЛ_ВО) if COL_КОЛ_ВО in df.columns else pd.Series(1.0, index=df.index)
    qty = qty.where(qty != 0, 1.0)
    df["_шт"] = qty.where(df["_есть_продажа"] == 1, 0) - qty.where(df["_есть_возврат"] == 1, 0)
    gross_col = next((c for c in GROSS_COLUMNS if c in df.columns), None)
    if gross_col:
        gross = safe_col(df, gross_col)
        df["_брутто"] = gross.where(маска_продажа & (обоснование == "продажа"), 0) - \
            gross.where(маска_возврат, 0).abs()
    else:
        df["_брутто"] = доход_продажи
    name_col = next((c for c in NAME_COLUMNS if c in df.columns), None)
    df["_название"] = df[name_col].fillna("").astype(str).str.strip() if name_col else ""

    # Поездки «туда-обратно» без выкупа (реальный отчёт: «… при отмене»)
    if COL_ВИДЫ in df.columns:
        df["_отмена"] = df[COL_ВИДЫ].astype(str).str.lower().str.contains("отмен", na=False).astype(int)
    else:
        df["_отмена"] = 0

    grouped = df.groupby("_артикул").agg(
        доход=("_доход_продажи", "sum"),
        логистика=("_логистика", "sum"),
        штрафы=("_штрафы", "sum"),
        хранение=("_хранение", "sum"),
        приёмка=("_приёмка", "sum"),
        удержания=("_удержания", "sum"),
        поездок=("_есть_логистика", "sum"),
        продаж_колво=("_есть_продажа", "sum"),
        возвратов=("_есть_возврат", "sum"),
        отмен=("_отмена", "sum"),
        шт=("_шт", "sum"),
        выручка_брутто=("_брутто", "sum"),
        название=("_название", lambda x: next((v for v in x if v and v != "nan"), "")),
    )
    grouped["чистая_прибыль"] = (
        grouped["доход"]
        - grouped["логистика"]
        - grouped["штрафы"]
        - grouped["хранение"]
        - grouped["приёмка"]
        - grouped["удержания"]
    )

    return {
        "marketplace": "WB",
        "доход": float(общий_доход),
        "логистика": float(общая_логистика),
        "штрафы": float(общие_штрафы),
        "хранение": float(общее_хранение),
        "приёмка": float(общая_приёмка),
        "удержания": float(общие_удержания),
        "чистая_прибыль": float(чистая_прибыль),
        "grouped": grouped,
        "rows": _history_rows(df, DATE_COLUMNS),
    }


def _history_rows(df: pd.DataFrame, date_columns) -> pd.DataFrame:
    """Построчные данные для истории продаж: дата, артикул, штуки, выплата, выручка."""
    date_col = next((c for c in date_columns if c in df.columns), None)
    rows = pd.DataFrame({
        "дата": df[date_col] if date_col else pd.Series(None, index=df.index, dtype=object),
        "артикул": df["_артикул"],
        "шт": df["_шт"],
        "выплата": df["_доход_продажи"] - df["_логистика"] - df["_штрафы"]
                   - df["_хранение"] - df["_приёмка"] - df["_удержания"],
        "выручка": df["_брутто"],
    })
    return rows


def analyze(filepath: str, m: dict | None = None) -> str:
    """
    Основная логика анализа.
    Возвращает HTML-отформатированный текстовый отчёт (str).
    m — уже посчитанные метрики compute(), чтобы не читать файл второй раз.
    """
    if m is None:
        m = compute(filepath)
    grouped = m["grouped"]
    общий_доход     = m["доход"]
    общая_логистика = m["логистика"]
    общие_штрафы    = m["штрафы"]
    общее_хранение  = m["хранение"]
    общая_приёмка   = m["приёмка"]
    общие_удержания = m["удержания"]
    чистая_прибыль  = m["чистая_прибыль"]

    lines = []
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
    lines.append("📊 <b>ОБЩИЙ ФИНАНСОВЫЙ ИТОГ</b>")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
    lines.append(f"  💰 Доход (продажи − возвраты): {fmt(общий_доход)} руб.")
    lines.append(f"  🚚 Логистика:         {fmt_expense(общая_логистика)} руб.")
    lines.append(f"  🔴 Штрафы:            {fmt_expense(общие_штрафы)} руб.")
    lines.append(f"  📦 Хранение:          {fmt_expense(общее_хранение)} руб.")
    lines.append(f"  🏭 Приёмка:           {fmt_expense(общая_приёмка)} руб.")
    lines.append(f"  📋 Удержания:         {fmt_expense(общие_удержания)} руб.")
    lines.append("▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️")
    
    profit_icon = "✅" if чистая_прибыль >= 0 else "🔻"
    lines.append(f"  {profit_icon} <b>К ВЫПЛАТЕ ОТ WB:    {fmt(чистая_прибыль)} руб.</b>")
    lines.append("  <i>до себестоимости и налогов</i>")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

    lines.append("")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
    lines.append("🏷 <b>ПРИБЫЛЬ ПО АРТИКУЛАМ</b>")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

    for артикул, row in grouped.iterrows():
        if not артикул:
            label = "⚙️ (общие расходы)"
        else:
            label = f"🔹 {артикул}"
        lines.append(f"\n  <b>{label}</b>")
        lines.append(f"    💰 Доход:      {fmt(row['доход'])} руб. • 🛠 {int(row.get('поездок', 0))} поездок | 🛒 {int(row.get('продаж_колво', 0))} продаж")
        lines.append(f"    🚚 Логистика:  {fmt_expense(row['логистика'])} руб.")
        lines.append(f"    🔴 Штрафы:     {fmt_expense(row['штрафы'])} руб.")
        lines.append(f"    📦 Хранение:   {fmt_expense(row['хранение'])} руб.")
        lines.append(f"    🏭 Приёмка:    {fmt_expense(row['приёмка'])} руб.")
        lines.append(f"    📋 Удержания:  {fmt_expense(row['удержания'])} руб.")
        итого_icon = "✅" if row["чистая_прибыль"] >= 0 else "🚨"
        if row["чистая_прибыль"] < 0:
            lines.append(
                f"    {итого_icon} <b>Чистый убыток по артикулу: "
                f"{fmt_profit(row['чистая_прибыль'])} руб.</b>"
            )
        else:
            lines.append(
                f"    {итого_icon} Итого: {fmt_profit(row['чистая_прибыль'])} руб."
            )

    # Топ-3 убыточных артикулов
    артикулы_only = grouped[grouped.index != ""]
    if not артикулы_only.empty:
        убыточные = артикулы_only.nsmallest(3, "чистая_прибыль")
        min_profit = убыточные.iloc[0]["чистая_прибыль"]
        header_text = "ТОП-3 УБЫТОЧНЫХ ТОВАРА" if min_profit < 0 else "ТОП-3 НАИМЕНЕЕ ПРИБЫЛЬНЫХ ТОВАРА"

        lines.append("")
        lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
        lines.append(f"⚠️ <b>{header_text}</b>")
        lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

        for i, (артикул, row) in enumerate(убыточные.iterrows(), 1):
            причины = {
                "Логистика": row["логистика"],
                "Штрафы":    row["штрафы"],
                "Хранение":  row["хранение"],
                "Приёмка":   row["приёмка"],
                "Удержания": row["удержания"],
            }
            главная_причина = max(причины, key=причины.get)
            главная_сумма   = причины[главная_причина]

            status_icon = "🔻" if row["чистая_прибыль"] < 0 else "⚠️"
            status = "УБЫТОК" if row["чистая_прибыль"] < 0 else "мин. прибыль"
            lines.append(f"\n  {i}. {status_icon} [{status}] <b>{артикул}</b>")
            поездок = int(row.get('поездок', 0))
            продаж_колво = int(row.get('продаж_колво', 0))
            if поездок > 0 or продаж_колво > 0:
                lines.append(f"     🛠 {поездок} поездок | 🛒 {продаж_колво} продаж")
            lines.append(f"     Чистая прибыль: {fmt_profit(row['чистая_прибыль'])} руб.")
            if главная_сумма > 0:
                lines.append(f"     Основной расход: {главная_причина} ({fmt(главная_сумма)} руб.)")

            # Инсайт «Советник»
            insight = generate_insight(артикул, row)
            if insight:
                lines.append(f"     {insight}")

    # ABC-анализ по чистой прибыли
    lines.extend(render_abc(grouped["чистая_прибыль"]))

    lines.append("")
    lines.append("📊 Присылай отчёт каждую неделю и сравнивай динамику: /compare")
    # Рекламный футер с тарифами добавляет bot.py — и только тем, кто ещё не оплатил

    return "\n".join(lines)


