"""
wb_parser.py — Анализ детализированного финансового отчёта Wildberries.

Рефакторинг: функция analyze() возвращает строку вместо print().

Поддерживает два формата входных файлов:
  - CSV  (.csv)
  - Excel (.xlsx / .xls)

И два набора столбцов (автоматическое определение):
  A) Формат реального отчёта WB:
     - 'К перечислению за товар', 'Стоимость логистики',
     - 'Общая сумма штрафов', 'Стоимость хранения', 'Стоимость платной приемки'
  B) Упрощённый формат:
     - 'К перечислению Продавцу за реализованный товар',
     - 'Услуги по доставке товара покупателю',
     - 'Общая сумма штрафов', 'Хранение', 'Операции при приёмке', 'Удержания'

Вывод: HTML-форматированный текст с эмодзи.
"""

import sys
import os
import pandas as pd

# ─── Маппинг столбцов ───────────────────────────────────────────────────────

# Формат A — реальный отчёт WB
COLUMNS_A = {
    "артикул":       "Артикул поставщика",
    "обоснование":   "Обоснование для оплаты",
    "доход":         "К перечислению за товар",
    "логистика":     "Стоимость логистики",
    "штрафы":        "Общая сумма штрафов",
    "хранение":      "Стоимость хранения",
    "приёмка":       "Стоимость платной приемки",
}

# Формат B — тестовый / упрощённый
COLUMNS_B = {
    "артикул":       "Артикул поставщика",
    "обоснование":   "Обоснование для оплаты",
    "доход":         "К перечислению Продавцу за реализованный товар",
    "логистика":     "Услуги по доставке товара покупателю",
    "штрафы":        "Общая сумма штрафов",
    "хранение":      "Хранение",
    "приёмка":       "Операции при приёмке",
    "удержания":     "Удержания",
}


def detect_column_mapping(df: pd.DataFrame) -> dict:
    """Автоматически определяет формат отчёта по наличию столбцов."""
    cols = set(df.columns)
    if COLUMNS_A["доход"] in cols:
        return COLUMNS_A
    if COLUMNS_B["доход"] in cols:
        return COLUMNS_B
    return COLUMNS_B


def safe_col(df: pd.DataFrame, col_name: str) -> pd.Series:
    """Безопасно возвращает столбец; если его нет — серию нулей."""
    if col_name in df.columns:
        return pd.to_numeric(df[col_name], errors="coerce").fillna(0)
    return pd.Series(0, index=df.index)


def load_report(filepath: str) -> pd.DataFrame:
    """Читает CSV или Excel-файл."""
    ext = os.path.splitext(filepath)[1].lower()
    if ext == ".csv":
        return pd.read_csv(filepath, encoding="utf-8-sig")
    elif ext in (".xlsx", ".xls"):
        return pd.read_excel(filepath)
    else:
        raise ValueError(f"Неподдерживаемый формат файла: {ext}. Нужен .csv или .xlsx")


def fmt(value: float) -> str:
    """Форматирует число с разделителями тысяч и 2 знаками после запятой."""
    return f"{value:,.2f}"


def bold(text: str) -> str:
    """Оборачивает текст в HTML-тег <b>."""
    return f"<b>{text}</b>"


def fmt_expense(value: float) -> str:
    """Форматирует расход: если > 0, выделяет жирным как отрицательный."""
    if value > 0:
        return bold(f"-{fmt(value)}")
    return fmt(value)


def fmt_profit(value: float) -> str:
    """Форматирует прибыль: отрицательные — жирным."""
    if value < 0:
        return bold(fmt(value))
    return fmt(value)


def generate_insight(артикул: str, row) -> str:
    """
    Генерирует текстовый инсайт «Советник» для конкретного артикула,
    указывая на реальные боли: покатушки, отказы, подмены на ПВЗ.
    """
    доход = row["доход"]
    логистика = row["логистика"]
    штрафы = row["штрафы"]
    удержания = row["удержания"]
    хранение = row["хранение"]
    приёмка = row["приёмка"]
    
    причины = {
        "логистика": логистика,
        "штрафы": штрафы,
        "хранение": хранение,
        "приёмка": приёмка,
        "удержания": удержания,
    }
    
    max_key = max(причины, key=причины.get)
    сумма = причины[max_key]

    if сумма <= 0:
        return ""

    # Сценарий 1: Атака конкурентов ("покатушки")
    if доход <= 0 and логистика > 0:
        return (
            f"💡 <b>Атака конкурентов («покатушки»):</b> выручка 0 руб., а логистика сожрала {fmt(логистика)} руб. "
            f"Товар массово заказывают без выкупа. Ограничьте географию продаж или повысьте цену."
        )

    процент = round((сумма / доход * 100) if доход > 0 else 0)

    # Сценарий 2: Глубокий минус из-за возвратов
    if max_key == "логистика":
        if процент >= 40:
            return (
                f"💡 <b>Сплошные отказы:</b> логистика съедает {процент}% выручки ({fmt(логистика)} руб.). "
                f"Вероятно, плохой % выкупа. Проверьте отзывы, размерную сетку или выводите товар из оборота."
            )
        return f"💡 <b>Рекомендация:</b> логистика забирает {процент}%. Проверьте габариты упаковки."

    # Сценарий 3: Потери / подмены на ПВЗ (штрафы и удержания)
    if max_key in ("штрафы", "удержания"):
        return (
            f"💡 <b>Потери на ПВЗ:</b> подозрительно высокие {max_key} ({fmt(сумма)} руб.). "
            f"Возможны подмены покупателями или утери на ПВЗ. Сформируйте обращение в поддержку с требованием компенсации."
        )

    if max_key == "хранение":
        return f"💡 <b>Рекомендация:</b> высокие расходы на хранение ({fmt(сумма)} руб.). Товар завис, добавьте его в акцию."

    return f"💡 <b>Рекомендация:</b> обратите внимание на {max_key} ({fmt(сумма)} руб.)."


def analyze(filepath: str) -> str:
    """
    Основная логика анализа.
    Возвращает HTML-отформатированный текстовый отчёт (str).
    """
    df = load_report(filepath)
    col = detect_column_mapping(df)

    col_артикул     = col.get("артикул", "Артикул поставщика")
    col_обоснование = col.get("обоснование", "Обоснование для оплаты")
    col_доход       = col.get("доход", "")
    col_логистика   = col.get("логистика", "")
    col_штрафы      = col.get("штрафы", "")
    col_хранение    = col.get("хранение", "")
    col_приёмка     = col.get("приёмка", "")
    col_удержания   = col.get("удержания", "")

    # Безопасно получаем числовые серии
    доход_все     = safe_col(df, col_доход)
    логистика_все = safe_col(df, col_логистика)
    штрафы_все    = safe_col(df, col_штрафы)
    хранение_все  = safe_col(df, col_хранение)
    приёмка_все   = safe_col(df, col_приёмка)
    удержания_все = safe_col(df, col_удержания)

    # Маска «Продажа»
    if col_обоснование in df.columns:
        маска_продажа = df[col_обоснование].astype(str).str.strip().str.lower() == "продажа"
    else:
        маска_продажа = pd.Series(True, index=df.index)

    доход_продажи = доход_все.where(маска_продажа, 0)

    # A) Общая чистая прибыль
    общий_доход     = доход_продажи.sum()
    общая_логистика = логистика_все.sum()
    общие_штрафы    = штрафы_все.sum()
    общее_хранение  = хранение_все.sum()
    общая_приёмка   = приёмка_все.sum()
    общие_удержания = удержания_все.sum()
    общие_расходы   = общая_логистика + общие_штрафы + общее_хранение + общая_приёмка + общие_удержания
    чистая_прибыль  = общий_доход - общие_расходы

    lines = []
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
    lines.append("📊 <b>ОБЩИЙ ФИНАНСОВЫЙ ИТОГ</b>")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
    lines.append(f"  💰 Доход (продажи):   {fmt(общий_доход)} руб.")
    lines.append(f"  🚚 Логистика:         {fmt_expense(общая_логистика)} руб.")
    lines.append(f"  🔴 Штрафы:            {fmt_expense(общие_штрафы)} руб.")
    lines.append(f"  📦 Хранение:          {fmt_expense(общее_хранение)} руб.")
    lines.append(f"  🏭 Приёмка:           {fmt_expense(общая_приёмка)} руб.")
    lines.append(f"  📋 Удержания:         {fmt_expense(общие_удержания)} руб.")
    lines.append("▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️ ▫️")
    
    profit_icon = "✅" if чистая_прибыль >= 0 else "🔻"
    lines.append(f"  {profit_icon} <b>ЧИСТАЯ ПРИБЫЛЬ:    {fmt(чистая_прибыль)} руб.</b>")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

    # Б) Чистая прибыль по каждому артикулу
    df["_доход_продажи"] = доход_продажи
    df["_логистика"]     = логистика_все
    df["_штрафы"]        = штрафы_все
    df["_хранение"]      = хранение_все
    df["_приёмка"]       = приёмка_все
    df["_удержания"]     = удержания_все

    if col_артикул in df.columns:
        df["_артикул"] = df[col_артикул].fillna("").astype(str).str.strip()
    else:
        df["_артикул"] = ""

    grouped = df.groupby("_артикул").agg(
        доход=("_доход_продажи", "sum"),
        логистика=("_логистика", "sum"),
        штрафы=("_штрафы", "sum"),
        хранение=("_хранение", "sum"),
        приёмка=("_приёмка", "sum"),
        удержания=("_удержания", "sum"),
    )
    grouped["чистая_прибыль"] = (
        grouped["доход"]
        - grouped["логистика"]
        - grouped["штрафы"]
        - grouped["хранение"]
        - grouped["приёмка"]
        - grouped["удержания"]
    )

    lines.append("")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
    lines.append("🏷 <b>ПРИБЫЛЬ ПО АРТИКУЛАМ</b>")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

    for артикул, row in grouped.iterrows():
        if not артикул:
            label = "⚙️ (общие расходы)"
        else:
            label = f"🔹 {артикул}"
        lines.append(f"\n  <b>{label}</b>")
        lines.append(f"    💰 Доход:      {fmt(row['доход'])} руб.")
        lines.append(f"    🚚 Логистика:  {fmt_expense(row['логистика'])} руб.")
        lines.append(f"    🔴 Штрафы:     {fmt_expense(row['штрафы'])} руб.")
        lines.append(f"    📦 Хранение:   {fmt_expense(row['хранение'])} руб.")
        lines.append(f"    🏭 Приёмка:    {fmt_expense(row['приёмка'])} руб.")
        lines.append(f"    📋 Удержания:  {fmt_expense(row['удержания'])} руб.")
        итого_icon = "✅" if row["чистая_прибыль"] >= 0 else "🔻"
        lines.append(f"    ▫️ {итого_icon} Итого: {fmt_profit(row['чистая_прибыль'])} руб.")

    # Топ-3 убыточных артикулов
    артикулы_only = grouped[grouped.index != ""]
    if not артикулы_only.empty:
        убыточные = артикулы_only.nsmallest(3, "чистая_прибыль")
        min_profit = убыточные.iloc[0]["чистая_прибыль"]
        header_text = "ТОП-3 УБЫТОЧНЫХ ТОВАРА" if min_profit < 0 else "ТОП-3 НАИМЕНЕЕ ПРИБЫЛЬНЫХ ТОВАРА"

        lines.append("")
        lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")
        lines.append(f"⚠️ <b>{header_text}</b>")
        lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

        for i, (артикул, row) in enumerate(убыточные.iterrows(), 1):
            причины = {
                "Логистика": row["логистика"],
                "Штрафы":    row["штрафы"],
                "Хранение":  row["хранение"],
                "Приёмка":   row["приёмка"],
                "Удержания": row["удержания"],
            }
            главная_причина = max(причины, key=причины.get)
            главная_сумма   = причины[главная_причина]

            status_icon = "🔻" if row["чистая_прибыль"] < 0 else "⚠️"
            status = "УБЫТОК" if row["чистая_прибыль"] < 0 else "мин. прибыль"
            lines.append(f"\n  {i}. {status_icon} [{status}] <b>{артикул}</b>")
            lines.append(f"     Чистая прибыль: {fmt_profit(row['чистая_прибыль'])} руб.")
            if главная_сумма > 0:
                lines.append(f"     Основной расход: {главная_причина} ({fmt(главная_сумма)} руб.)")

            # Инсайт «Советник»
            insight = generate_insight(артикул, row)
            if insight:
                lines.append(f"     {insight}")

    lines.append("")
    lines.append("➖➖➖➖➖➖➖➖➖➖➖➖")

    return "\n".join(lines)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Использование: python wb_parser.py <путь_к_файлу.csv|xlsx>")
        sys.exit(1)

    filepath = sys.argv[1]
    if not os.path.exists(filepath):
        print(f"Файл не найден: {filepath}")
        sys.exit(1)

    print(analyze(filepath))
