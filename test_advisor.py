"""Smoke-тест логики Советника (3 боли + false-positive guard)."""
import pandas as pd
from wb_parser import generate_insight

def check(name, cond):
    print(f"{name}: {'✅ OK' if cond else '❌ FAIL'}")
    assert cond, name

# TEST 1: 1 поездка + 0 продаж → НЕ должно быть Боли 1 (false positive guard)
row1 = pd.Series({
    "доход": 0, "логистика": 500, "штрафы": 0, "удержания": 0,
    "хранение": 0, "приёмка": 0, "чистая_прибыль": -500,
    "поездок": 1, "продаж_колво": 0,
})
out1 = generate_insight("TEST-1", row1)
check("TEST1 (1 поездка — НЕ триггерит Боль 1)", "аномалия" not in out1.lower())
print(f"   output: {out1!r}")

# TEST 2: 3 поездки + 0 продаж → ДОЛЖНА быть Боль 1
row2 = pd.Series({
    "доход": 0, "логистика": 1200, "штрафы": 0, "удержания": 0,
    "хранение": 0, "приёмка": 0, "чистая_прибыль": -1200,
    "поездок": 3, "продаж_колво": 0,
})
out2 = generate_insight("TEST-2", row2)
check("TEST2 (3 поездки — Боль 1)", "🚨" in out2 and "проверьте регион" in out2)
print(f"   output: {out2[:120]}...")

# TEST 3a: >40% чека + В ПЛЮСЕ → "жёлтая зона" (НЕ "юнит-экономику")
row3a = pd.Series({
    "доход": 1000, "логистика": 300, "штрафы": 200, "удержания": 50,
    "хранение": 0, "приёмка": 0, "чистая_прибыль": 450,
    "поездок": 5, "продаж_колво": 2,
})
out3a = generate_insight("TEST-3a", row3a)
check("TEST3a (55% чека, в ПЛЮСЕ → жёлтая зона)",
      "📉" in out3a and "с маленькой маржой" in out3a and "юнит-экономику" not in out3a)
print(f"   output: {out3a[:150]}...")

# TEST 3b: >40% чека + В МИНУСЕ → рекомендация поднять цену
row3b = pd.Series({
    "доход": 1000, "логистика": 500, "штрафы": 100, "удержания": 0,
    "хранение": 0, "приёмка": 0, "чистая_прибыль": -200,
    "поездок": 5, "продаж_колво": 2,
})
out3b = generate_insight("TEST-3b", row3b)
# Доля = 60%, недостача = 100 - 60 + 30 = 70%, средний_чек = 1000 → наценка ~700
# Проверяем, что в фразе "Поднимите цену на <b>... руб.</b>" не стоит 0.00
# NB: между числом и </b> идёт " руб." — поэтому regex использует ([\d,\.]+).*?</b>
import re
m = re.search(r"Поднимите цену на <b>([\d,\.]+).*?</b>", out3b)
наценка = m.group(1) if m else ""
ok = (
    "📉" in out3b
    and "юнит-экономику" in out3b
    and m is not None
    and наценка not in ("0.00", "0", "0,00")
)
check("TEST3b (60% чека, В МИНУСЕ → наценка > 0 и не '0.00')", ok)
print(f"   output: {out3b[:200]}...")
print(f"   parsed 'Поднимите цену на': {наценка!r}")

# TEST 3c: 50% чека + В ПЛЮСЕ + РЕАЛЬНЫЙ КЕЙС (как MARGIN-DEAD-07)
row3c = pd.Series({
    "доход": 3200, "логистика": 1600, "штрафы": 0, "удержания": 0,
    "хранение": 0, "приёмка": 0, "чистая_прибыль": 1600,
    "поездок": 4, "продаж_колво": 4,
})
out3c = generate_insight("MARGIN-DEAD-07", row3c)
# В этой ветке НЕ должно быть "Поднимите цену на X руб."
check("TEST3c (MARGIN-DEAD-07 — 50% чека, в плюсе → нет 'Поднимите цену')",
      "📉" in out3c and "Поднимите цену" not in out3c and "снизьте" in out3c.lower())
print(f"   output: {out3c[:200]}...")

# TEST 4: штрафы без реализации → ДОЛЖНА быть Боль 3
row4 = pd.Series({
    "доход": 0, "логистика": 0, "штрафы": 1500, "удержания": 0,
    "хранение": 0, "приёмка": 0, "чистая_прибыль": -1500,
    "поездок": 0, "продаж_колво": 0,
})
out4 = generate_insight("TEST-4", row4)
check("TEST4 (штрафы без продаж — Боль 3)", "⚠️" in out4 and "тикет в поддержку" in out4)
print(f"   output: {out4[:120]}...")

# TEST 5: здоровый артикул → пусто
row5 = pd.Series({
    "доход": 5000, "логистика": 500, "штрафы": 100, "удержания": 0,
    "хранение": 200, "приёмка": 50, "чистая_прибыль": 4150,
    "поездок": 10, "продаж_колво": 8,
})
out5 = generate_insight("TEST-5", row5)
check("TEST5 (здоровый артикул — пустой инсайт)", out5 == "")
print(f"   output: {out5!r}")

print("\n🎉 Все 7 тестов пройдены!")